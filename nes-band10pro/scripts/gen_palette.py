#!/usr/bin/env python3
"""Generate the 64-entry NES master-palette -> RGB565 table used by frame.rs.

Source palette: the classic 2C02 NTSC rendering used by NESdev/FCEUX, ordered
by PPU palette index 0x00..0x3F. It is an approximate NTSC rendering, which is
what every software NES palette is; the important property for this task is a
stable 64-entry index -> RGB565 mapping shared by host and device code.
"""
from pathlib import Path

NES_PALETTE_RGB = [
    # 0x00..0x0F
    (0x62, 0x62, 0x62), (0x00, 0x1F, 0xB2), (0x24, 0x04, 0xC8), (0x52, 0x00, 0xCC),
    (0x73, 0x00, 0xB4), (0x8C, 0x00, 0x70), (0xA0, 0x00, 0x38), (0xA0, 0x10, 0x00),
    (0x8A, 0x2C, 0x00), (0x60, 0x50, 0x00), (0x34, 0x6C, 0x00), (0x00, 0x80, 0x00),
    (0x00, 0x84, 0x50), (0x00, 0x78, 0x88), (0x00, 0x68, 0x9C), (0x00, 0x00, 0x00),
    # 0x10..0x1F
    (0xBC, 0xBC, 0xBC), (0x00, 0x70, 0xEC), (0x44, 0x28, 0xFC), (0x82, 0x18, 0xFC),
    (0xB0, 0x10, 0xE4), (0xD8, 0x00, 0xA0), (0xE4, 0x00, 0x58), (0xE4, 0x20, 0x00),
    (0xCC, 0x50, 0x00), (0xA8, 0x84, 0x00), (0x74, 0xA8, 0x00), (0x3C, 0xA8, 0x00),
    (0x14, 0xB8, 0x00), (0x00, 0xB0, 0x40), (0x00, 0xA8, 0xA0), (0x00, 0x00, 0x00),
    # 0x20..0x2F
    (0xFC, 0xFC, 0xFC), (0x3C, 0xBC, 0xFC), (0x68, 0x88, 0xFC), (0x98, 0x78, 0xFC),
    (0xC0, 0x78, 0xFC), (0xE8, 0x68, 0xF8), (0xF8, 0x58, 0x98), (0xFC, 0x58, 0x60),
    (0xF8, 0x78, 0x30), (0xFC, 0xA0, 0x00), (0xF8, 0xD8, 0x00), (0xC0, 0xE0, 0x00),
    (0x88, 0xE8, 0x00), (0x50, 0xF0, 0x50), (0x38, 0xF0, 0xA8), (0x00, 0x00, 0x00),
    # 0x30..0x3F
    (0xFC, 0xFC, 0xFC), (0xA8, 0xE4, 0xFC), (0xB8, 0xB8, 0xFC), (0xD8, 0xA8, 0xFC),
    (0xF0, 0xA8, 0xF8), (0xFC, 0xA8, 0xE0), (0xFC, 0xA8, 0xB8), (0xFC, 0xB0, 0xA0),
    (0xFC, 0xC0, 0x88), (0xFC, 0xD8, 0x70), (0xFC, 0xE8, 0x58), (0xD8, 0xF8, 0x58),
    (0xB8, 0xF8, 0x78), (0xA0, 0xF0, 0xA8), (0x98, 0xF0, 0xD8), (0x00, 0x00, 0x00),
]


def rgb565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main() -> int:
    assert len(NES_PALETTE_RGB) == 64
    values = [rgb565(*rgb) for rgb in NES_PALETTE_RGB]
    lines = []
    for row in range(8):
        chunk = values[row * 8 : row * 8 + 8]
        lines.append("    " + " ".join(f"0x{v:04X}," for v in chunk))
    body = "\n".join(lines)
    print(f"pub const NES_PALETTE_RGB565: [u16; 64] = [\n{body}\n];")
    out = Path(__file__).resolve().parents[1] / "build" / "palette_rgb565.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
